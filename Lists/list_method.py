nums = [10 , 20 , 30 ,40 ,50]

# to add nums

nums.append(100)
print(nums)

# insert num

nums.insert(2,36)
print(nums)

#remove the num

nums.remove(20)
print(nums)

# remove last num

nums.pop()
print(nums)

#sort list
nums.sort()
print(nums)

#reverse

nums.reverse()
print(nums)

#clear the list
nums.clear()
print(nums)

#lenght
nums = [10 ,20 ,30 ,40]
print(len(nums))

